#!/usr/bin/env python3
"""Generate docs/clinical/rule-review-sheet.md: everything the product and clinical requirements lead (and later the
independent reviewer) must read to review the Phase 1 clinical logic, generated from the live rule file, catalogue,
calculator tables and reference cases so the sheet can never drift from the code.

    python scripts/gen_review_sheet.py           # write
    python scripts/gen_review_sheet.py --check   # exit 1 if the committed sheet is out of date
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "packages" / "core" / "src"))

from cnai import calculators  # noqa: E402
from cnai.models import Catalogue, RuleSet  # noqa: E402

OUT = ROOT / "docs" / "clinical" / "rule-review-sheet.md"


def md_row(cells):
    return "| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in cells) + " |"


def build() -> str:
    cat = Catalogue.load()
    rs = RuleSet.load("adult_general")
    raw = rs.raw
    ref = yaml.safe_load((ROOT / "tests" / "reference" / "calculator_reference_cases.yaml").read_text())
    synth = json.loads((ROOT / "data" / "synthetic" / "adult" / "index.json").read_text())
    adult = [e for e in cat.elements.values() if e.enabled]
    paed = [e for e in cat.elements.values() if not e.enabled]

    L = []
    L += ["# Clinical review sheet: adult general pathway (Phase 1)", "",
          "GENERATED by `scripts/gen_review_sheet.py` from the rule file, catalogue, calculators and reference cases. "
          "Do not edit by hand; change the source and regenerate.", "",
          f"- Rule set: **{rs.rule_set} v{rs.version}**, review status **{rs.review_status}**",
          f"- Data-element catalogue: **v{cat.version}**, review status **{cat.review_status}**",
          f"- Pathway registry: v{cat.pathways_version}",
          f"- Reference cases: **{ref['status']}**", "",
          "## How to use this sheet", "",
          "This sheet lists every clinical judgement built into Phase 1. Nothing here is a clinical standard until the "
          "product and clinical requirements lead has reviewed it, and it is not independently reviewed until the independent "
          "clinical safety reviewer has. Sign-off is recorded in `docs/clinical/rule-signoff.md`, which is edited by hand "
          "by the reviewer, never by the generator.", "",
          "Questions to ask of each section are given in italics.", ""]

    L += ["## 1. Active pathway and age bands", "",
          md_row(["Pathway", "Status", "Min age (months)", "Max age (months)"]), md_row(["---"] * 4)]
    for p in cat.pathways.values():
        L.append(md_row([f"`{p.code}`", p.status, p.min_age_months, p.max_age_months if p.max_age_months is not None else "none"]))
    L += ["", "_Is 18 years (216 months) the correct start of the adult pathway for your setting? Are the planned paediatric "
              "and SAM age bands right as placeholders?_", ""]

    L += ["## 2. Data elements in the adult pathway", "",
          md_row(["Element", "Label", "Type", "Unit", "Plausible range", "Stale after (days)", "Conflict tolerance", "Undated OK"]),
          md_row(["---"] * 8)]
    for e in adult:
        rng = f"{e.plausible_min} to {e.plausible_max}" if e.plausible_min is not None else "n/a"
        L.append(md_row([f"`{e.code}`", e.label, e.value_type + (f" ({', '.join(e.allowed_values)})" if e.allowed_values else ""),
                         e.canonical_unit or "", rng, e.staleness_days if e.staleness_days is not None else "none",
                         e.conflict_tolerance if e.conflict_tolerance is not None else "n/a", "yes" if e.undated_ok else "no"]))
    L += ["", "_Plausible ranges are wide bounds that only catch entry and unit errors; they are not reference ranges. Are any "
              "too narrow (a real patient would be wrongly flagged) or too wide? Are the staleness windows right for your "
              "inpatient and outpatient practice? Is anything missing that you always assess?_", ""]

    L += ["## 3. Completeness rules: what counts as a gap", "",
          md_row(["Rule", "Element", "Criticality", "Applies when", "Why it is asked"]), md_row(["---"] * 5)]
    for r in raw["completeness"]:
        cond = r.get("applies_when") or {}
        when = "; ".join(f"{k} in {v}" for k, v in cond.items()) or "always"
        L.append(md_row([f"{r['id']} v{r['version']}", f"`{r['element']}`", r["criticality"], when, r["why"]]))
    L += ["", "_`blocking` means the assessment should not be treated as complete without it. Is each criticality what you "
              "would assign? Is any `why` text misleading, directive or clinically wrong?_", ""]

    cnf = raw["conflicts"]
    L += ["## 4. Conflict, staleness, implausible-value and scope rules", "",
          f"- **{cnf['same_day_disagreement']['id']}**: two live records of one element on one date that differ in status, or "
          "numeric values further apart than the element's conflict tolerance. Blocking for: "
          f"{', '.join('`'+k+'`' for k in cnf['same_day_disagreement']['criticality_by_element'])}; otherwise "
          f"{cnf['same_day_disagreement']['default_criticality']}."]
    for p in cnf["pairs"]:
        L.append(f"- **{p['id']}**: `{p['a']['element']}` ({', '.join(f'{k} {v}' for k, v in p['a'].items() if k != 'element')}) "
                 f"with `{p['b']['element']}` ({', '.join(f'{k} {v}' for k, v in p['b'].items() if k != 'element')}). "
                 f"Criticality {p['criticality']}.")
    st = raw["staleness"]
    L.append(f"- **{st['id']}**: value older than the element's staleness window, or undated (criticality {st['criticality']}).")
    L.append(f"- **{raw['implausible']['id']}**: value outside the plausible range, wrong or missing unit, not an allowed code, "
             "or dated after the assessment. The value is treated as unreliable and never used in a calculation.")
    for s in raw["scope_exclusions"]:
        L.append(f"- **{s['id']}** (scope exclusion): refuse analysis when `{s['element']}` is one of "
                 f"{', '.join(s['refuse_if_value_in'])}.")
    L += ["", "_Are there other populations or conditions that should be refused rather than analysed (for example, on a "
              "dialysis or tube-feeding pathway)? Should any conflict rule be added or removed?_", ""]

    L += ["## 5. Calculations", "",
          "| Formula | Definition | Notes |", "| --- | --- | --- |",
          "| `bmi` v1 | weight (kg) / height (m) squared; most recent valid dated weight and any valid height | WHO adult categories below |",
          "| `pct_weight_change_vs_previous` v1 | (current - previous) / previous x 100, previous = latest valid weight on an earlier date | No significance threshold applied |",
          "| `pct_weight_change_vs_usual` v1 | (current - usual) / usual x 100, usual = reported usual weight | No significance threshold applied |", "",
          f"Reference for BMI categories as coded: {calculators.WHO_BMI['citation']} ({calculators.WHO_BMI['verification']}).", "",
          md_row(["BMI below", "Category"]), md_row(["---", "---"])]
    for upper, label in calculators.BMI_CUTOFFS:
        L.append(md_row([upper, label]))
    L.append(md_row(["40 and above", calculators.BMI_TOP_LABEL]))
    L += ["", "_Do these cut-offs match the classification you use? Do you want ethnicity-specific cut-offs? Energy and protein "
              "estimation is deliberately not implemented yet; which equations and stress or activity factors would you choose?_", ""]

    L += ["## 6. Unit conversions", "", md_row(["Element", "Accepted units (to canonical)"]), md_row(["---", "---"])]
    from cnai.units import CONVERSIONS
    for code, table in CONVERSIONS.items():
        L.append(md_row([f"`{code}`", ", ".join(sorted(table))]))
    L += ["", "_Check the conversion factors in `packages/core/src/cnai/units.py`: glucose 18.0156 mg/dL per mmol/L, creatinine "
              "88.4 umol/L per mg/dL, phosphate 0.3229 mmol/L per mg/dL, magnesium 0.4114 mmol/L per mg/dL._", ""]

    L += ["## 7. Disabled paediatric placeholders", "",
          "Registered but refused by the engine and the database until their pathway is activated (D-018):", ""]
    for e in paed:
        L.append(f"- `{e.code}`: {e.label}")
    L.append("")

    L += ["## 8. Reference cases awaiting verification", "",
          f"Status: **{ref['status']}**. {len(ref['bmi'])} BMI cases, {len(ref['pct_weight_change_vs_previous'])} weight-change cases and "
          f"{len(ref['unit_conversions'])} unit-conversion cases in `tests/reference/calculator_reference_cases.yaml`, with expected "
          "values computed independently of the engine. _Please check the formulas, inputs, expected values and category "
          "boundaries, then set `status: verified`, `verified_by` and `verified_on` in that file._", ""]

    L += ["## 9. Synthetic trap cases", "",
          f"{synth['count']} invented cases in `data/synthetic/adult/`, each with a hand-written expectation. Please read the "
          "titles and confirm they are clinically realistic and that nothing important is missing:", ""]
    for c in synth["cases"]:
        L.append(f"- `{c['case_id']}` {c['title']}")
    L += ["", "## 10. Review actions", "",
          "1. Read sections 1 to 6 and mark any change you want.",
          "2. Verify section 8.",
          "3. Record your decision in `docs/clinical/rule-signoff.md` (author approval) and, when appointed, the independent "
          "reviewer records theirs.",
          "4. A rule's `review_status` in the rule file is changed only after sign-off is recorded."]
    return "\n".join(L) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("DRIFT: docs/clinical/rule-review-sheet.md is out of date; run scripts/gen_review_sheet.py")
            return 1
        print("review sheet is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
