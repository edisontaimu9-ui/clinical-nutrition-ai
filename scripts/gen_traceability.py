#!/usr/bin/env python3
"""Generate docs/TRACEABILITY.md from REQUIREMENTS.md, the roadmap's Phase 1 list and docs/traceability_map.yaml.

    python scripts/gen_traceability.py           # write
    python scripts/gen_traceability.py --check   # fail if stale, or if the map names a test that does not exist,
                                                 # or if a Phase 1 requirement has no entry
"""
import ast
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "TRACEABILITY.md"
MAP = ROOT / "docs" / "traceability_map.yaml"
PHASE2 = "FR-AUD-01 FR-AUD-03 FR-ADM-01 FR-GOV-03 NFR-SEC-01 NFR-SEC-02 NFR-SEC-03 NFR-SEC-04 NFR-SEC-05 NFR-REL-01".split()
PHASE1 = ("FR-INT-01 FR-INT-02 FR-INT-04 FR-INT-05 FR-STATE-01 FR-STATE-02 FR-COMP-01 FR-COMP-02 FR-COMP-03 "
          "FR-CALC-01 FR-CALC-02 FR-CALC-03 FR-CALC-04 FR-CONF-01 FR-CONF-02 FR-POP-01 FR-POP-02 FR-POP-03 FR-POP-04 "
          "FR-GOV-01 FR-GOV-02 NFR-SEC-06 NFR-SEC-07 NFR-MNT-01 NFR-MNT-02 NFR-MNT-03 NFR-INT-01 NFR-OBS-01 NFR-PERF-01").split()


def requirements():
    out = {}
    for m in re.finditer(r"^\| ((?:FR|NFR)-[A-Z]+-\d{2}) \| (.*?) \|", (ROOT / "REQUIREMENTS.md").read_text(), re.M):
        out[m.group(1)] = m.group(2)
    return out


def test_exists(spec: str) -> bool:
    path, _, name = spec.partition("::")
    f = ROOT / path
    if not f.exists():
        return False
    tree = ast.parse(f.read_text())
    return any(isinstance(n, ast.FunctionDef) and n.name == name for n in ast.walk(tree))


def problems(reqs, evidence):
    errs = []
    for r in PHASE1 + PHASE2:
        if r not in reqs:
            errs.append(f"{r} is not defined in REQUIREMENTS.md")
        if r not in evidence:
            errs.append(f"{r} has no entry in docs/traceability_map.yaml")
    for r, e in evidence.items():
        if r not in reqs:
            errs.append(f"traceability map names unknown requirement {r}")
        if e["status"] not in ("automated", "partial", "documentary"):
            errs.append(f"{r}: bad status {e['status']!r}")
        if e["status"] == "automated" and not e.get("tests"):
            errs.append(f"{r}: marked automated but names no tests")
        if e["status"] == "partial" and not e.get("note"):
            errs.append(f"{r}: partial coverage needs a note saying what is not covered")
        for t in e.get("tests") or []:
            if not test_exists(t):
                errs.append(f"{r}: test not found: {t}")
    return errs


def table(reqs, evidence, ids):
    L = ["| Requirement | Summary | Status | Evidence | Not yet covered / notes |", "| --- | --- | --- | --- | --- |"]
    for r in ids:
        e = evidence[r]
        text = reqs[r]
        text = text if len(text) < 110 else text[:107].rstrip() + "..."
        ev = "<br>".join(f"`{t.split('/')[-1]}`" for t in (e.get("tests") or [])) or "document"
        L.append("| " + " | ".join([r, text.replace("|", "\\|"), e["status"], ev, (e.get("note") or "").replace("|", "\\|")]) + " |")
    return L


def summary(evidence, ids):
    c = {s: sum(1 for r in ids if evidence[r]["status"] == s) for s in ("automated", "partial", "documentary")}
    return (f"Requirements: {len(ids)}. Fully covered by automated tests: **{c['automated']}**. "
            f"Partly covered: **{c['partial']}**. Evidenced by documents: **{c['documentary']}**.")


def build(reqs, evidence) -> str:
    L = ["# Traceability: requirements to evidence", "",
         "GENERATED by `scripts/gen_traceability.py` from `docs/traceability_map.yaml`. Edit the map, not this file.", "",
         "\"Automated\" means a test fails if the behaviour breaks. It does not mean clinically validated or deployed: the clinical "
         "content still needs the sign-off in `docs/clinical/rule-signoff.md`, and infrastructure items (TLS, key management, "
         "the identity provider) are not built yet. Where a requirement is only partly covered, the last column says what is missing.", "",
         "## Phase 1: adult data model and deterministic core", "", summary(evidence, PHASE1), ""]
    L += table(reqs, evidence, PHASE1)
    L += ["", "## Phase 2: security and audit baseline", "", summary(evidence, PHASE2), ""]
    L += table(reqs, evidence, PHASE2)
    return "\n".join(L) + "\n"


def main() -> int:
    reqs = requirements()
    evidence = yaml.safe_load(MAP.read_text())
    errs = problems(reqs, evidence)
    if errs:
        print("\n".join("ERROR: " + e for e in errs))
        return 1
    text = build(reqs, evidence)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("DRIFT: docs/TRACEABILITY.md is out of date; run scripts/gen_traceability.py")
            return 1
        print("traceability is up to date")
        return 0
    OUT.write_text(text)
    print("wrote docs/TRACEABILITY.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
