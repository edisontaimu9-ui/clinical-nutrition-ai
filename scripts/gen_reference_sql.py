#!/usr/bin/env python3
"""Generate db/migrations/0004_reference_data.sql from packages/schemas/*.json.

The JSON files are the single source of truth for the pathway registry and the data-element catalogue. The
migration is generated, committed, and checked for drift in CI (`--check`).

Usage:
    python scripts/gen_reference_sql.py           # write the migration
    python scripts/gen_reference_sql.py --check   # exit 1 if the committed file differs
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "db" / "migrations" / "0004_reference_data.sql"


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def arr(values, empty="'{}'"):
    if values is None:
        return "NULL"
    if not values:
        return empty
    return "ARRAY[" + ", ".join(lit(x) for x in values) + "]::text[]"


def build() -> str:
    pathways = json.loads((ROOT / "packages/schemas/pathways.json").read_text())
    elements = json.loads((ROOT / "packages/schemas/data_elements.json").read_text())
    lines = [
        "-- 0004_reference_data: pathway registry and data-element catalogue.",
        "-- GENERATED by scripts/gen_reference_sql.py from packages/schemas/*.json. Do not edit by hand.",
        f"-- pathways {pathways['version']}, data elements {elements['version']} (review status: {elements['review_status']}).",
        "",
        "INSERT INTO clinical.pathway (pathway_code, label, status, min_age_months, max_age_months, activated_by_decision) VALUES",
    ]
    rows = []
    for p in pathways["pathways"]:
        rows.append("  (" + ", ".join(lit(p[k]) for k in (
            "pathway_code", "label", "status", "min_age_months", "max_age_months", "activated_by_decision")) + ")")
    lines.append(",\n".join(rows) + ";")
    lines += [
        "",
        "INSERT INTO clinical.data_element_def",
        "  (element_code, domain, label, value_type, canonical_unit, plausible_min, plausible_max, staleness_days,",
        "   conflict_tolerance, allowed_values, undated_ok, enabled, pathways, min_age_months, max_age_months) VALUES",
    ]
    rows = []
    for e in elements["elements"]:
        rows.append("  (" + ", ".join([
            lit(e["element_code"]), lit(e["domain"]), lit(e["label"]), lit(e["value_type"]),
            lit(e.get("canonical_unit")), lit(e.get("plausible_min")), lit(e.get("plausible_max")),
            lit(e.get("staleness_days")), lit(e.get("conflict_tolerance")),
            arr(e.get("allowed_values")) if e.get("allowed_values") else "NULL",
            lit(e.get("undated_ok", False)), lit(e.get("enabled", True)), arr(e.get("pathways", [])),
            lit(e.get("min_age_months")), lit(e.get("max_age_months")),
        ]) + ")")
    lines.append(",\n".join(rows) + ";")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("DRIFT: db/migrations/0004_reference_data.sql is out of date; run scripts/gen_reference_sql.py")
            return 1
        print("reference-data migration is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
